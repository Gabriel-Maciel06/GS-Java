-- 0. LIMPEZA PRÉVIA IDEMPOTENTE (Ordem inversa de dependência de chaves)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS TB_PROTOCOLO_DEFESA_CIVIL CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS TB_OCORRENCIA CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS TB_CIDADAO CASCADE CONSTRAINTS;

-- ----------------------------------------------------------------------------
-- 1. TABELA TB_CIDADAO
-- ----------------------------------------------------------------------------
CREATE TABLE TB_CIDADAO (
    id_cidadao NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome VARCHAR2(150) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    telefone VARCHAR2(20),
    bairro VARCHAR2(100) NOT NULL,
    senha VARCHAR2(255) NOT NULL,
    role VARCHAR2(30) DEFAULT 'ROLE_CIDADAO' NOT NULL,
    data_cadastro TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ativo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_TB_CIDADAO PRIMARY KEY (id_cidadao),
    CONSTRAINT UK_CIDADAO_EMAIL UNIQUE (email),
    CONSTRAINT CK_CIDADAO_ATIVO CHECK (ativo IN (0, 1)),
    CONSTRAINT CK_CIDADAO_ROLE CHECK (role IN ('ROLE_CIDADAO', 'ROLE_GESTOR'))
);

-- ----------------------------------------------------------------------------
-- 2. TABELA TB_OCORRENCIA
-- ----------------------------------------------------------------------------
CREATE TABLE TB_OCORRENCIA (
    id_ocorrencia NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cidadao_id NUMBER(19) NOT NULL,
    titulo VARCHAR2(120) NOT NULL,
    descricao VARCHAR2(1000) NOT NULL,
    categoria VARCHAR2(30) NOT NULL,
    severidade VARCHAR2(20) NOT NULL,
    status VARCHAR2(35) DEFAULT 'ABERTA' NOT NULL,
    latitude NUMBER(10, 7),
    longitude NUMBER(10, 7),
    endereco VARCHAR2(255) NOT NULL,
    bairro VARCHAR2(100) NOT NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP,
    CONSTRAINT PK_TB_OCORRENCIA PRIMARY KEY (id_ocorrencia),
    CONSTRAINT FK_OCORRENCIA_CIDADAO FOREIGN KEY (cidadao_id) 
        REFERENCES TB_CIDADAO (id_cidadao) ON DELETE CASCADE,
    CONSTRAINT CK_OCORRENCIA_CATEGORIA CHECK (categoria IN (
        'ALAGAMENTO', 'BUEIRO_OBSTRUIDO', 'DESLIZAMENTO', 
        'QUEDA_ARVORE', 'ENXURRADA', 'EROSAO_SOLO', 'OUTROS'
    )),
    CONSTRAINT CK_OCORRENCIA_SEVERIDADE CHECK (severidade IN (
        'BAIXA', 'MEDIA', 'ALTA', 'CRITICA'
    )),
    CONSTRAINT CK_OCORRENCIA_STATUS CHECK (status IN (
        'ABERTA', 'EM_ANALISE', 'ENCAMINHADA_DEFESA_CIVIL', 
        'EM_ATENDIMENTO', 'RESOLVIDA', 'CANCELADA'
    ))
);

-- Índices de alta performance para consultas geográficas, status e severidade
CREATE INDEX IDX_OCORRENCIA_BAIRRO ON TB_OCORRENCIA (bairro);
CREATE INDEX IDX_OCORRENCIA_STATUS ON TB_OCORRENCIA (status);
CREATE INDEX IDX_OCORRENCIA_SEVERIDADE ON TB_OCORRENCIA (severidade);
CREATE INDEX IDX_OCORRENCIA_CIDADAO ON TB_OCORRENCIA (cidadao_id);

-- ----------------------------------------------------------------------------
-- 3. TABELA TB_PROTOCOLO_DEFESA_CIVIL
-- ----------------------------------------------------------------------------
CREATE TABLE TB_PROTOCOLO_DEFESA_CIVIL (
    id_protocolo NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ocorrencia_id NUMBER(19) NOT NULL,
    numero_protocolo VARCHAR2(30) NOT NULL,
    equipe_responsavel VARCHAR2(100) NOT NULL,
    parecer_tecnico VARCHAR2(1500),
    data_emissao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_previsao_atendimento TIMESTAMP,
    data_conclusao TIMESTAMP,
    CONSTRAINT PK_TB_PROTOCOLO PRIMARY KEY (id_protocolo),
    CONSTRAINT UK_PROTOCOLO_NUMERO UNIQUE (numero_protocolo),
    CONSTRAINT UK_PROTOCOLO_OCORRENCIA UNIQUE (ocorrencia_id),
    CONSTRAINT FK_PROTOCOLO_OCORRENCIA FOREIGN KEY (ocorrencia_id) 
        REFERENCES TB_OCORRENCIA (id_ocorrencia) ON DELETE CASCADE
);

CREATE INDEX IDX_PROTOCOLO_NUMERO ON TB_PROTOCOLO_DEFESA_CIVIL (numero_protocolo);
